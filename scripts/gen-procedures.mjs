#!/usr/bin/env node
// Regenerates lib/procedures.generated.ts from docs/openapi.json
// (https://app.tinkerer.club/api/v1/openapi.json). Output: every procedure
// path, so tinkerer_call can validate names and agents can list them
// without the 340 KB spec (which carries no summaries).
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(resolve(here, "..", "docs", "openapi.json"), "utf8"));
const rows = [];
for (const [path, item] of Object.entries(spec.paths)) {
  const op = item.post;
  if (!op) continue;
  const name = path.replace(/^\/api\/v1\//, "");
  const summary = (op.summary ?? op.description ?? "").replace(/\s+/g, " ").trim().slice(0, 140);
  rows.push({ name, summary });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const lines = [
  "// Generated by scripts/gen-procedures.mjs from docs/openapi.json. Do not edit.",
  `// ${rows.length} procedures, spec version ${spec.info?.version ?? "?"}.`,
  "export const PROCEDURES: readonly string[] = [",
  ...rows.map((r) => `  ${JSON.stringify(r.name)},`),
  "];",
  "",
];
writeFileSync(resolve(here, "..", "lib", "procedures.generated.ts"), lines.join("\n"));
console.log(`wrote ${rows.length} procedures`);
